#!/usr/bin/env python3
"""Generates each app's config from the private quicknotes.config.json.

    python3 scripts/configure.py        (build.sh and deploy.sh run this for you)

quicknotes.config.json and every file written here are git-ignored, so project
keys and IDs never land in the repository. Start from quicknotes.config.example.json.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "quicknotes.config.json"
HEADER = "Generated by scripts/configure.py from quicknotes.config.json. Do not edit; do not commit."

if not CONFIG.exists():
    sys.exit(
        "Missing quicknotes.config.json.\n"
        "  cp quicknotes.config.example.json quicknotes.config.json\n"
        "and fill in your Firebase project's values (see README → Configuration)."
    )

cfg = json.loads(CONFIG.read_text())
fb = cfg["firebase"]
placeholders = [k for k, v in {**fb, "webURL": cfg["webURL"]}.items() if "YOUR_" in str(v)]
if placeholders:
    sys.exit(f"quicknotes.config.json still has placeholder values for: {', '.join(placeholders)}")

project = fb["projectId"]
web_url = cfg["webURL"] if cfg["webURL"].endswith("/") else cfg["webURL"] + "/"
link_url = f"https://{fb['authDomain']}/link"  # sign-in must run on the auth domain (Google's authorized redirect)
sites = cfg["hostingSites"]
extension_id = cfg["extensionId"]


def write(rel, text):
    path = ROOT / rel
    path.write_text(text)
    print(f"  wrote {rel}")


js = json.dumps

write("web/firebase-config.js", f"""// {HEADER}
export const firebaseConfig = {json.dumps(fb, indent=2)};

export const NOTES_COLLECTION = "qn_notes";
export const USERS_COLLECTION = "users";
// the Chrome extension allowed to receive sign-ins from /link
export const EXTENSION_ID = {js(extension_id)};
""")

write("extension/config.js", f"""// {HEADER}
export const CONFIG = {{
  apiKey: {js(fb["apiKey"])},
  projectId: {js(project)},
  collection: "qn_notes",
  webURL: {js(web_url)},
  // served from the auth domain so Google sign-in stays same-origin inside Chrome's sign-in window
  linkURL: {js(link_url)},
}};
""")

write("desktop/Config.swift", f"""// {HEADER}
import Foundation

enum CloudConfig {{
    static let apiKey = {js(fb["apiKey"])}
    static let projectId = {js(project)}
    static let webURL = URL(string: {js(web_url)})!
    /// Served from the auth domain itself, so the redirect sign-in stays same-origin inside the macOS sheet.
    static let linkURL = URL(string: {js(link_url)})!
    static let collection = "qn_notes"
    static let callbackScheme = "quicknotes"
}}
""")

write(".firebaserc", json.dumps({"projects": {"default": project}}, indent=2) + "\n")

# Deploy config: the same web/ folder goes to every hosting site. The project's default
# site must be among them, because sign-in runs on <project-id>.firebaseapp.com/link.
HOSTING = {
    "public": "web",
    "cleanUrls": True,
    "ignore": ["**/.*"],
    "headers": [{
        "source": "**/*.@(html|js|css|webmanifest)",
        "headers": [{"key": "Cache-Control", "value": "no-cache"}],
    }],
}
all_sites = list(dict.fromkeys(sites + [project]))
write("firebase.json", json.dumps({
    "hosting": [{"site": site, **HOSTING} for site in all_sites],
    "firestore": {"rules": "firestore.rules"},
}, indent=2) + "\n")
